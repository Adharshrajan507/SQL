CREATE DATABASE PROJ;
USE PROJ;

SELECT * FROM CARDATASET;
SELECT COUNT(*) FROM CARDATASET;

DESCRIBE CARDATASET;
SELECT
    `Date`,
    STR_TO_DATE(`Date`, '%m/%d/%Y') AS Converted_Date,
    YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR,
    MONTH(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS MONTH_NUMBER,
    MONTHNAME(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS MONTH_NAME
FROM CARDATASET
LIMIT 10;


-- TOTAL REVENUE --

CREATE  VIEW TOTAL_REVENUE_VIEW AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR, SUM(`Price ($)`) AS TOTAL_REVENUE
FROM CARDATASET GROUP BY SALES_YEAR;

SELECT * FROM TOTAL_REVENUE_VIEW;

-- TOTAL SALES --
CREATE VIEW TOTAL_SALES_VIEW AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR, COUNT(Car_id) AS TOTAL_CARS_SOLD
FROM CARDATASET GROUP BY SALES_YEAR;

SELECT * FROM TOTAL_SALES_VIEW;

-- TOP COMPANY -- 
 CREATE VIEW TOP_COMPANY_VIEW AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR, Company, COUNT(Car_id) AS CARS_SOLD, SUM(`Price ($)`) AS TOTAL_REVENUE
FROM CARDATASET GROUP BY SALES_YEAR, Company;

SELECT * FROM TOP_COMPANY_VIEW;

-- TOP 10 CARS SOLD --
 
CREATE  VIEW TOP_10_CARS AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR, Company, Model, COUNT(Car_id) AS CARS_SOLD, SUM(`Price ($)`) AS TOTAL_REVENUE
FROM CARDATASET GROUP BY SALES_YEAR, Company, Model;


-- REGIONAL PERFORMANCE -- 

CREATE VIEW REGIONAL_SALES AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR,Dealer_Region,COUNT(Car_id) AS CARS_SOLD,SUM(`Price ($)`) AS TOTAL_REVENUE
FROM CARDATASET GROUP BY SALES_YEAR, Dealer_Region;


-- TRANSMISSION PREFERENCE --

CREATE VIEW TRANSMISSION_VIEW AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR,Transmission,COUNT(Car_id) AS CARS_SOLD
FROM CARDATASET GROUP BY SALES_YEAR, Transmission;

-- BODY STYLE --
  
CREATE  VIEW BODY_STYLE AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR,`Body Style`,COUNT(Car_id) AS CARS_SOLD,SUM(`Price ($)`) AS TOTAL_REVENUE
FROM CARDATASET GROUP BY SALES_YEAR, `Body Style`;

-- TOP 10 DEALERS -- 

CREATE VIEW TOP_10_DEALERS AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR,Dealer_Name,Dealer_Region,COUNT(Car_id) AS CARS_SOLD,SUM(`Price ($)`) AS TOTAL_REVENUE
FROM CARDATASET GROUP BY SALES_YEAR, Dealer_Name, Dealer_Region;

-- MONTHLY REVENUE -- 

CREATE VIEW MONTHLY_REVENUE AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR,MONTH(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS MONTH_NUMBER,MONTHNAME(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS MONTH_NAME,SUM(`Price ($)`) AS TOTAL_REVENUE
FROM CARDATASET GROUP BY SALES_YEAR, MONTH_NUMBER, MONTH_NAME;

-- COMPANY WISE BODY STYLE -- 

CREATE VIEW COMPANY_BODY_STYLE AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR, Company, `Body Style`, COUNT(Car_id) AS CARS_SOLD, SUM(`Price ($)`) AS TOTAL_REVENUE
FROM CARDATASET GROUP BY SALES_YEAR, Company, `Body Style`;

-- COMPANY WISE SALES --

CREATE OR REPLACE VIEW company_monthly_sales_view AS
SELECT YEAR(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS SALES_YEAR,MONTH(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS MONTH_NUMBER,MONTHNAME(STR_TO_DATE(`Date`, '%m/%d/%Y')) AS MONTH_NAME,Company,COUNT(Car_id) AS CARS_SOLD
FROM CARDATASET GROUP BY SALES_YEAR,MONTH_NUMBER,MONTH_NAME,Company;

SHOW FULL TABLES WHERE TABLE_TYPE = 'VIEW';



